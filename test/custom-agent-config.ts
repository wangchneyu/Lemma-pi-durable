import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { loadConfig } from "../src/config.ts";
import { agentAdapter } from "../src/agents.ts";
import { demoConfig } from "../src/demo.ts";
import { detectAgents } from "../src/tools.ts";
import { memberToolNames } from "../src/api-member.ts";
import { check } from "./helpers.ts";
const directory = mkdtempSync(join(tmpdir(), "lemma-role-config-"));
const file = join(directory, "config.json");
const agent = { name: "资料分析员", instructions: "Use supplied evidence", models: [{ id: "configured-model", tier: "standard" }], api: { type: "anthropic-compatible", baseUrl: "https://example.invalid", apiKeyEnv: ["LEMMA_FIXTURE_ROLE_KEY"] } };
const read = (value: object) => { writeFileSync(file, JSON.stringify(value)); return loadConfig(file); };
const config = read({ agents: { researcher: agent } });
assert.equal(config.agents.researcher.defaultModel, "configured-model");
assert.equal(config.agents.researcher.workspace, "none");
assert.deepEqual(config.agents.researcher.api!.tools, []);
assert.deepEqual(memberToolNames({ ...config.agents.researcher.api!, tools: ["read", "bash"], bash: "off" }), ["read"]);
assert.equal(agentAdapter("researcher", config.agents.researcher).label, "资料分析员");
assert(config.roles.some((role) => role.agent === "claude"));
assert.equal(detectAgents(config).find((a) => a.kind === "researcher")?.available, false);
for (const id of ["constructor", "prototype", "lead", "all", "orchestrator", "bad-name", "Bad"]) assert.throws(() => read({ agents: { [id]: agent } }), /无效成员/);
assert.throws(() => read({ agents: { researcher: { description: "missing API" } } }), /api 配置/);
assert.throws(() => read({ agents: { researcher: { ...agent, api: { ...agent.api, tools: ["delete_all"] } } } }), /api.tools/);
assert.throws(() => read({ agents: { researcher: { ...agent, api: { ...agent.api, baseUrl: "https://secret:password@example.invalid" } } } }), /不包含凭据/);
assert.throws(() => read({ agents: { researcher: { ...agent, workspace: "automatic" } } }), /workspace/);
assert.throws(() => read({ agents: { researcher: agent }, roles: [{ name: "bad", agent: "absent" }] }), /roles/);
assert.throws(() => read({ collaboration: { instructions: 42 } }), /instructions/);
const legacy = read({ agents: { deepseek: { defaultModel: "legacy-model" } } });
assert.equal(legacy.agents.deepseek.workspace, "code");
assert.equal(legacy.agents.deepseek.api!.tools, undefined);
assert(legacy.roles.length > 0);
check(true, "配置：自定义身份与 API 协议分离、权限默认关闭，旧成员/角色配置兼容且无效输入被拒绝");
const demo = demoConfig(config);
assert.equal(demo.agents.researcher.enabled, false);
check(true, "演示隔离：原有演示剧本不会误调用自定义真实 API 成员");
const browserUtil = new URL("../web/js/util.js", import.meta.url).href;
const { KINDS, AGENT_LABEL, setAgentLabels, agentColor, esc } = await import(browserUtil);
setAgentLabels([{ kind: "researcher", label: "资料分析员" }, { kind: "reviewer", label: "<em>review</em>" }]);
assert(KINDS.includes("researcher") && KINDS.includes("reviewer"));
assert.equal(AGENT_LABEL.researcher, "资料分析员");
assert(agentColor("researcher").startsWith("hsl("));
assert.equal(esc(AGENT_LABEL.reviewer), "&lt;em&gt;review&lt;/em&gt;");
setAgentLabels([]); assert(!KINDS.includes("researcher"));
check(true, "网页目录：自定义成员进入筛选与统计，使用稳定颜色，名称按文本转义");
