import assert from "node:assert/strict";
import { BACKGROUND_CONTEXT } from "@earendil-works/chord/context";
import { createModels } from "@earendil-works/pi-ai";
import { fauxAssistantMessage, fauxProvider } from "@earendil-works/pi-ai/providers/faux";
import { LiveDoc, type TaskId } from "@earendil-works/pi-durable";
import { openApp } from "../src/app.ts";
import { nativeModelCatalog, selectControllerModel } from "../src/model-selection.ts";
import { createOrchestratorModel } from "../src/models.ts";
import { check, testConfig } from "./helpers.ts";

const context = BACKGROUND_CONTEXT;
const config = testConfig();
for (const agent of Object.values(config.agents)) agent.enabled = false;
const faux = fauxProvider({ provider: "controller-test", models: [{ id: "first" }, { id: "second" }] });
const models = createModels(); models.setProvider(faux.provider);
const model = { models, ref: { provider: "controller-test", modelId: "first" } };
let app = await openApp(config, model, context);
try {
	await app.root.commit((tx) => tx.appendEntry(app.root.id, { kind: "pi.user", model: [{ role: "user", content: "保存历史但不执行模型", timestamp: Date.now() }] }), context);
	const before = (await app.root.entries({}, 100, undefined, context)).items;
	await selectControllerModel(app.harness, app.root, models, model.ref.provider, { provider: model.ref.provider, id: "second" }, context);
	assert.equal((await app.root.agent(context)).model?.modelId, "second");
	assert.deepEqual((await app.root.entries({}, 100, undefined, context)).items, before);
	check(true, "切换模型只写 Durable pi.agent，原始历史不改变");
	await app.harness.close(context);
	app = await openApp(config, model, context);
	assert.equal((await app.root.agent(context)).model?.modelId, "second");
	check(true, "相同启动配置下重启恢复本会话选择的模型");
	const isolatedConfig = testConfig();
	for (const agent of Object.values(isolatedConfig.agents)) agent.enabled = false;
	const isolated = await openApp(isolatedConfig, model, context);
	try { assert.equal((await isolated.root.agent(context)).model?.modelId, "first"); } finally { await isolated.harness.close(context); }
	check(true, "另一独立会话继续使用自己的模型选择");
	let receivedModel = "";
	faux.setResponses([(_request, _options, _state, actual) => { receivedModel = actual.id; return fauxAssistantMessage("SECOND_MODEL_OK"); }]);
	const submission = await app.root.submit({ type: "input", content: "检查选中模型" }, context);
	app.harness.resume();
	await submission.wait(context);
	assert.equal(receivedModel, "second");
	check(true, "下一次实际模型请求使用 Durable 中选中的模型");
	await assert.rejects(selectControllerModel(app.harness, app.root, models, model.ref.provider, { provider: "member", id: "second" }, context), /目录/);
	await assert.rejects(selectControllerModel(app.harness, app.root, models, model.ref.provider, { provider: model.ref.provider, id: "missing" }, context), /目录/);
	await app.root.commit(async (tx) => { (await tx.doc(LiveDoc, app.root.id)).run = { taskId: 900 as TaskId, inputs: [], turns: 0 }; }, context);
	await assert.rejects(selectControllerModel(app.harness, app.root, models, model.ref.provider, { provider: model.ref.provider, id: "first" }, context), /运行中/);
	await app.root.commit(async (tx) => { delete (await tx.doc(LiveDoc, app.root.id)).run; }, context);
	assert.equal((await app.root.agent(context)).model?.modelId, "second");
	check(true, "拒绝运行中切换和目录外模型，失败不修改已选模型");
	const calls = faux.state.callCount;
	const catalog = await nativeModelCatalog(models, model.ref.provider);
	await catalog.refresh();
	assert.deepEqual(catalog.getAvailableSnapshot().map((item) => item.id), ["first", "second"]);
	assert.equal(catalog.getModel("other", "first"), undefined);
	assert.equal(faux.state.callCount, calls);
	await app.harness.close(context);
	app = await openApp(config, { ...model, ref: { ...model.ref, modelId: "second" } }, context);
	assert.equal((await app.root.agent(context)).model?.modelId, "second");
	await app.harness.close(context);
	app = await openApp(config, model, context);
	assert.equal((await app.root.agent(context)).model?.modelId, "first");
	check(true, "显式修改启动默认模型后更新 Durable，目录刷新不调用模型");
	const configured = createOrchestratorModel({ type: "openai-compatible", modelId: "base", modelIds: ["fast", "base"], baseUrl: "http://127.0.0.1:1/v1", apiKeyEnv: [] });
	assert.deepEqual(configured.models.getModels("orchestrator").map((item) => item.id), ["base", "fast"]);
	check(true, "中转模型目录只使用显式配置的模型 ID，不猜测服务支持范围");
} finally { await app.harness.close(context); }
