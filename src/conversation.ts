/** 只描述运行时已确认的配置；模型标识不保证中转服务的真实上游。 */
export function conversationIdentity(input: PromptInput): string {
	const model = input.agent.model;
	return [
		LEMMA_IDENTITY,
		input.conversationId === ROOT_CONVERSATION_ID
			? "当前角色：你是用户正在对话的 Lemma 总调度，也可以直接陪用户讨论与解答问题。"
			: "当前角色：你是 Lemma 内的子对话；遵守本对话专门配置的角色、子目标和范围，不冒充总调度或扩大授权。",
		`当前对话 ID：${input.conversationId}（只在所属存储内唯一）。`,
		model
			? `当前请求的配置模型标识：${model.provider}/${model.modelId}；这是配置标识，不证明中转服务的真实上游模型。`
			: "当前未配置模型，不猜测基础模型身份。",
		`当前工作目录：${input.agent.cwd ?? input.env?.cwd ?? "未指定"}。目录只表示操作位置，不表示已读取其中的项目内容。`,
	].join("\n");
}
